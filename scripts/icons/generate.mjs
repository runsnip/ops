// generate.mjs — the page's icon sprite, made on a development machine (never on a server): the exact icons the
// page and `runsnip graph` use, from a pinned @runsnip/icons version, drawn with its toSvg into one <svg> of
// <symbol>s committed as internal/serve/web/icons.svg (served by go:embed, used as <svg><use href="#i-name">).
//
//   node scripts/icons/generate.mjs            (downloads the pinned version with npm into a temporary folder)
//   RUNSNIP_ICONS_PKG=<folder> node scripts/icons/generate.mjs   (or --pkg <folder>: a local checkout of the package,
//                                              built, at the pinned version — before that version is on npm)
//
// Placeholders (icons.json: placeholder: true) are stand-ins until @runsnip/icons draws the right one.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const cfg = JSON.parse(readFileSync(join(here, "icons.json"), "utf8"));
const flag = process.argv.indexOf("--pkg");
const local = flag >= 0 ? process.argv[flag + 1] : process.env.RUNSNIP_ICONS_PKG;
const tmp = mkdtempSync(join(tmpdir(), "runsnip-icons-"));
try {
  let pkg;
  if (local) {
    pkg = resolve(local);
  } else {
    execFileSync("npm", ["install", "--no-save", "--ignore-scripts", "--no-audit", "--no-fund", "--prefix", tmp, `${cfg.package}@${cfg.version}`], { stdio: "inherit" });
    pkg = join(tmp, "node_modules", ...cfg.package.split("/"));
  }
  const version = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version;
  if (version !== cfg.version) throw new Error(`got ${version}, pinned ${cfg.version}`);
  const lib = await import(pathToFileURL(join(pkg, "dist", "index.js")).href);
  const catalog = JSON.parse(readFileSync(join(pkg, "dist", "catalog.json"), "utf8"));
  const byFile = new Map(catalog.icons.map((i) => [i.file, i.name]));
  const symbols = [];
  for (const [name, e] of Object.entries(cfg.icons)) {
    const exp = byFile.get(e.icon);
    if (!exp || !lib[exp]) throw new Error(`${name}: ${e.icon} is not in ${cfg.package}@${version}`);
    if (e.placeholder) console.warn(`placeholder: ${name} drawn with ${e.icon}`);
    const svg = lib.toSvg(lib[exp], { size: 24 });
    const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? "0 0 24 24";
    const attrs = ["fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin"]
      .map((a) => { const m = new RegExp(`\\s${a}="([^"]+)"`).exec(svg.slice(0, svg.indexOf(">"))); return m ? ` ${a}="${m[1]}"` : ""; }).join("");
    const inner = svg.slice(svg.indexOf(">") + 1, svg.lastIndexOf("</svg>")).trim();
    symbols.push(`<symbol id="i-${name}" viewBox="${viewBox}"${attrs}>${inner}</symbol>`);
  }
  const out = `<svg xmlns="http://www.w3.org/2000/svg"><!-- ${cfg.package}@${version} (MIT, https://icons.runsnip.net), generated by scripts/icons/generate.mjs -->${symbols.join("")}</svg>\n`;
  writeFileSync(resolve(here, cfg.out), out);
  const ph = Object.entries(cfg.icons).filter(([, e]) => e.placeholder).map(([n]) => n);
  console.log(`${symbols.length} icons, ${out.length} bytes → ${cfg.out}${ph.length ? "; placeholders: " + ph.join(", ") : ""}`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
